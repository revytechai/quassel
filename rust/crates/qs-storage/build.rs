//! Generates the table of SQL statements the storage crate runs.
//!
//! The SQL lives in `sql/<backend>/`; it is a copy of the C++ core's
//! `src/core/SQL/<backend>/`, so the Rust core sets up exactly the schema the
//! C++ core sets up.  The test `the_sql_matches_the_cores` checks that the
//! copy has not drifted.

use std::env;
use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest_dir = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR"));
    let sql_root = manifest_dir.join("sql");
    println!("cargo:rerun-if-changed={}", sql_root.display());

    let mut out = String::new();
    out.push_str("// @generated by build.rs -- do not edit.\n\n");

    for (backend, prefix) in [("sqlite", "SQLITE"), ("postgresql", "POSTGRES")] {
        let dir = sql_root.join(backend);
        let setup = collect(&dir, "setup", None);
        let upgrades = collect_versions(&dir);
        check_versions(backend, &dir, &upgrades);

        out.push_str(&format!(
            "/// The setup statements of the {backend} backend, in the order the core runs them.\n"
        ));
        out.push_str(&format!(
            "pub const {upper}_SETUP: &[(&str, &str)] = &[\n",
            upper = prefix
        ));
        for (name, path) in &setup {
            out.push_str(&format!(
                "    ({:?}, include_str!({:?})),\n",
                name,
                path.to_string_lossy()
            ));
        }
        out.push_str("];\n\n");

        out.push_str(&format!(
            "/// The upgrade statements of the {backend} backend: (version, name, statement).\n"
        ));
        out.push_str(&format!(
            "pub const {upper}_UPGRADES: &[(u32, &str, &str)] = &[\n",
            upper = prefix
        ));
        for (version, name, path) in &upgrades {
            out.push_str(&format!(
                "    ({version}, {name:?}, include_str!({:?})),\n",
                path.to_string_lossy()
            ));
        }
        out.push_str("];\n\n");
    }

    let out_dir = PathBuf::from(env::var("OUT_DIR").expect("OUT_DIR"));
    fs::write(out_dir.join("schema_sql.rs"), out).expect("writing the generated schema");
}

/// Checks that the versions of a backend are contiguous.
///
/// A version directory without an upgrade statement, or a version that is
/// missing between two others, would make the core write a schema version
/// that the database does not have: the migration would run no statements
/// and the schema would stay behind.
fn check_versions(backend: &str, dir: &Path, upgrades: &[(u32, String, PathBuf)]) {
    let mut versions: Vec<u32> = Vec::new();
    let Ok(entries) = fs::read_dir(dir.join("version")) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if !path.is_dir() {
            continue;
        }
        let Some(version) = path
            .file_name()
            .and_then(|name| name.to_str())
            .and_then(|name| name.parse::<u32>().ok())
        else {
            panic!(
                "the {backend} schema has a version directory that is not a number: {}",
                path.display()
            );
        };
        versions.push(version);
    }
    versions.sort_unstable();
    let first = versions.first().copied().unwrap_or(0);
    for (index, version) in versions.iter().enumerate() {
        if *version != first + index as u32 {
            panic!(
                "the {backend} schema version {version} is missing: the versions must be contiguous"
            );
        }
        if !upgrades.iter().any(|(step, _, _)| *step == *version) {
            panic!("the {backend} schema version {version} has no upgrade statement");
        }
    }
}

/// Collects the `setup*.sql` files of a directory, sorted by name.
fn collect(dir: &Path, prefix: &str, version: Option<u32>) -> Vec<(String, PathBuf)> {
    let search_dir = match version {
        Some(version) => dir.join("version").join(version.to_string()),
        None => dir.to_path_buf(),
    };
    let Ok(entries) = fs::read_dir(&search_dir) else {
        return Vec::new();
    };
    let mut files: Vec<(String, PathBuf)> = entries
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| {
            path.file_name()
                .and_then(|name| name.to_str())
                .is_some_and(|name| name.starts_with(prefix) && name.ends_with(".sql"))
        })
        .map(|path| {
            let name = path.file_stem().unwrap().to_string_lossy().into_owned();
            (name, path)
        })
        .collect();
    files.sort_by(|left, right| left.0.cmp(&right.0));
    files
}

/// Collects the upgrade statements of every version directory.
fn collect_versions(dir: &Path) -> Vec<(u32, String, PathBuf)> {
    let Ok(entries) = fs::read_dir(dir.join("version")) else {
        return Vec::new();
    };
    let mut versions: Vec<u32> = entries
        .flatten()
        .map(|entry| entry.path())
        .filter(|path| path.is_dir())
        .filter_map(|path| {
            path.file_name()
                .and_then(|name| name.to_str())
                .and_then(|name| name.parse::<u32>().ok())
        })
        .collect();
    versions.sort_unstable();
    let mut out = Vec::new();
    for version in versions {
        for (name, path) in collect(dir, "upgrade", Some(version)) {
            out.push((version, name, path));
        }
    }
    out
}
